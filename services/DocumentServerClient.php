namespace humhub\modules\euro_office\services;

use humhub\libs\CURLHelper;
use humhub\modules\euro_office\models\Configuration;
use humhub\modules\euro_office\Module;
use RuntimeException;
use Yii;
use yii\httpclient\Client;
use yii\httpclient\CurlTransport;
use yii\httpclient\Response;

/**
 * Server-to-server requests from HumHub to the document server
 */
class DocumentServerClient
{
    public function __construct(private readonly Configuration $config)
    {
    }

    /**
     * @throws RuntimeException if the document server is not reachable or not ready
     */
    public function checkHealth(): void
    {
        $response = $this->get($this->config->getInternalServerUrl() . '/healthcheck');

        if (trim($response->getContent()) !== 'true') {
            throw new RuntimeException('Unexpected healthcheck response: ' . mb_substr($response->getContent(), 0, 100));
        }
    }

    /**
     * Downloads a file provided by the document server, e.g. the edited document in a callback
     *
     * @throws RuntimeException
     */
    public function download(string $url): string
    {
        return $this->get($this->toInternalUrl($url))->getContent();
    }

    /**
     * URLs generated by the document server point to its public address, which may not be reachable from HumHub
     */
    public function toInternalUrl(string $url): string
    {
        $public = $this->config->getPublicServerUrl();
        $internal = $this->config->getInternalServerUrl();

        if ($public !== $internal && str_starts_with($url, $public . '/')) {
            return $internal . substr($url, strlen($public));
        }

        return $url;
    }

    private function get(string $url): Response
    {
        /** @var Module $module */
        $module = Yii::$app->getModule('euro-office');

        $client = new Client(['transport' => CurlTransport::class]);
        $response = $client->get($url)
            ->setOptions($this->getCurlOptions($url))
            ->addOptions(['timeout' => $module->requestTimeout])
            ->send();

        if (!$response->isOk) {
            throw new RuntimeException('HTTP ' . $response->statusCode . ' for ' . $url);
        }

        return $response;
    }

    public function getCurlOptions(string $url): array
    {
        $options = CURLHelper::getOptions();

        if ($this->config->verifyPeerOff && str_starts_with(strtolower($url), 'https://')) {
            $options[CURLOPT_SSL_VERIFYPEER] = false;
            $options[CURLOPT_SSL_VERIFYHOST] = 0;
        }

        return $options;
    }
}
